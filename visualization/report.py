"""
PDF Performance Report generator using FPDF2.
"""

from fpdf import FPDF
import os
from datetime import datetime
from core.models import AnalysisResult
from utils.logging_utils import logger


class SportsPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(33, 150, 243)
        self.cell(0, 10, "AI SPORTS VIDEO ANALYSIS REPORT", border=False, new_x="LMARGIN", new_y="NEXT", align="C")
        self.set_draw_color(33, 150, 243)
        self.line(10, 20, 200, 20)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 9)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by AI Sports Video Analyser", align="C")


class ReportGenerator:
    """Generates structured PDF reports for video analysis sessions."""
    def __init__(self, result: AnalysisResult):
        self.result = result

    def generate(self, output_path: str) -> str:
        pdf = SportsPDF()
        pdf.add_page()
        pdf.set_font("Helvetica", "", 12)

        # 1. Video Info Section
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "1. Video Information", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 11)
        
        info = self.result.video_info
        if info:
            pdf.cell(0, 7, f"Filename: {info.filename}", new_x="LMARGIN", new_y="NEXT")
            pdf.cell(0, 7, f"Duration: {info.duration} seconds | FPS: {info.fps}", new_x="LMARGIN", new_y="NEXT")
            pdf.cell(0, 7, f"Resolution: {info.width}x{info.height} | Sport: {self.result.sport.capitalize()}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(5)

        # 2. Player Detections Summary
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "2. Player Detection & Tracking Summary", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 7, f"Total Unique Players Tracked: {self.result.get_player_count()}", new_x="LMARGIN", new_y="NEXT")
        pdf.cell(0, 7, f"Total Events Detected: {self.result.get_total_events()}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(5)

        # 3. Per Player Metrics & Feedback
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "3. Player Performance & AI Feedback", new_x="LMARGIN", new_y="NEXT")
        
        for pid in self.result.get_player_ids():
            perf = self.result.performance.get(pid)
            motion = self.result.motion_metrics.get(pid)
            fb = self.result.feedback.get(pid)

            pdf.set_font("Helvetica", "B", 12)
            pdf.cell(0, 8, f"--- Player {pid} ---", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 10)

            if perf:
                pdf.cell(0, 6, f"Prototype Score: {perf.overall_score}/100 (Grade: {perf.grade})", new_x="LMARGIN", new_y="NEXT")
            if motion:
                pdf.cell(0, 6, f"Estimated Distance: {motion.est_distance_m} m | Peak Speed: {motion.est_max_speed_kmh} km/h (Estimate)", new_x="LMARGIN", new_y="NEXT")
                pdf.cell(0, 6, f"Active Duration: {motion.active_duration_s}s | Stationary: {motion.stationary_duration_s}s", new_x="LMARGIN", new_y="NEXT")
            
            if fb:
                pdf.set_x(10)
                pdf.multi_cell(pdf.epw, 6, f"AI Feedback Summary: {fb.summary}", new_x="LMARGIN", new_y="NEXT")
                if fb.strengths:
                    pdf.set_x(10)
                    pdf.multi_cell(pdf.epw, 6, f"Strengths: {', '.join(fb.strengths)}", new_x="LMARGIN", new_y="NEXT")
                if fb.improvements:
                    pdf.set_x(10)
                    pdf.multi_cell(pdf.epw, 6, f"Areas for Improvement: {', '.join(fb.improvements)}", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(4)

        pdf.ln(5)
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_x(10)
        pdf.multi_cell(pdf.epw, 5, "DISCLAIMER: Performance scores are AI-generated prototype indicators extracted from video observations. Speed and distance values are pixel-based estimates. This report does not provide medical or biomechanical diagnosis.", new_x="LMARGIN", new_y="NEXT")

        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        pdf.output(output_path)
        logger.info(f"Generated PDF report at {output_path}")
        return output_path
